CREATE TABLE CERTIFICATE_CONFIG (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_NAME      VARCHAR2(150) NOT NULL,
    ENVIRONMENT_NAME      VARCHAR2(20) NOT NULL,
    CERTIFICATE_NAME      VARCHAR2(200) NOT NULL,
    OWNER_TEAM            VARCHAR2(150) NOT NULL,
    EMAIL_RECIPIENTS      VARCHAR2(2000) NOT NULL,
    EXPIRY_DATE           DATE NOT NULL,
    NOTES                 VARCHAR2(2000),
    ACTIVE_MONITORING     CHAR(1) DEFAULT 'Y' NOT NULL,
    ACKNOWLEDGED          CHAR(1) DEFAULT 'N' NOT NULL,
    ACKNOWLEDGED_BY       VARCHAR2(150),
    ACKNOWLEDGED_AT       TIMESTAMP,
    CREATED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT CK_CERT_ENV CHECK (
      ENVIRONMENT_NAME IN ('DEV','TEST','UAT','PROD','DR')
    ),
    CONSTRAINT CK_CERT_ACTIVE CHECK (
      ACTIVE_MONITORING IN ('Y','N')
    ),
    CONSTRAINT CK_CERT_ACK CHECK (
      ACKNOWLEDGED IN ('Y','N')
    )
);

CREATE TABLE CERTIFICATE_NOTIFICATION_HISTORY (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CERTIFICATE_ID        NUMBER NOT NULL,
    NOTIFICATION_TYPE     VARCHAR2(30) NOT NULL,
    RECIPIENTS            VARCHAR2(2000) NOT NULL,
    SUBJECT_LINE          VARCHAR2(500),
    SEND_STATUS           VARCHAR2(30) NOT NULL,
    ERROR_MESSAGE         VARCHAR2(2000),
    SENT_AT               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_CERT_NOTIF_CERT
      FOREIGN KEY (CERTIFICATE_ID)
      REFERENCES CERTIFICATE_CONFIG(ID),

    CONSTRAINT CK_CERT_NOTIF_TYPE CHECK (
      NOTIFICATION_TYPE IN ('D30','D15','D7','D3','D1','EXPIRED','MANUAL')
    ),

    CONSTRAINT CK_CERT_NOTIF_STATUS CHECK (
      SEND_STATUS IN ('SENT','FAILED')
    )
);

CREATE INDEX IX_CERT_CONFIG_EXPIRY
    ON CERTIFICATE_CONFIG(EXPIRY_DATE);

CREATE INDEX IX_CERT_CONFIG_ACTIVE
    ON CERTIFICATE_CONFIG(ACTIVE_MONITORING);

CREATE INDEX IX_CERT_NOTIF_CERT_ID
    ON CERTIFICATE_NOTIFICATION_HISTORY(CERTIFICATE_ID);

CREATE INDEX IX_CERT_NOTIF_SENT_AT
    ON CERTIFICATE_NOTIFICATION_HISTORY(SENT_AT);
